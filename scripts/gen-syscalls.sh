#!/bin/sh
# Regenerates internal/syscalls/table_*.go from the audit userspace syscall
# tables (ausyscall --dump). Runs inside the builder image (`make syscalls`),
# which pins the auditd version; both architectures come from one tool, so
# the host arch does not matter.
set -eu

out_dir=${1:-internal/syscalls}
ver=$(dpkg-query -W -f '${Version}' auditd)

gen() {
	arch=$1 var=$2 file=$3
	{
		echo "// Code generated by scripts/gen-syscalls.sh from ausyscall $arch --dump (auditd $ver); DO NOT EDIT."
		echo
		echo "package syscalls"
		echo
		echo "var $var = map[uint32]string{"
		ausyscall "$arch" --dump | awk 'NR > 1 && $1 ~ /^[0-9]+$/ { printf "\t%s: \"%s\",\n", $1, $2 }'
		echo "}"
	} >"$out_dir/$file"
	gofmt -w "$out_dir/$file"
}

gen x86_64 namesX86_64 table_x86.go
gen aarch64 namesAarch64 table_aarch64.go
